let bad = 0
for (const [p, ok] of CASES) {
  const lib = generateLibraryPage(p, 7, undefined, true, 'auto', undefined, true)
  const niche = typeof lib.niche === 'string' ? lib.niche : lib.niche?.id
  const cfg = appConfigFor(lib.content, { themeKey: lib.themeKey, niche })
  const kind = appKindOf({ themeKey: lib.themeKey, niche, subject: lib.content.subject, voice: lib.content.voice, prompt: [lib.content.subject, lib.content.hero.title, lib.content.hero.subtitle, lib.content.features.items.map((f) => f.title).join(' ')].join(' ') })
  if (!ok.includes(kind)) {
    bad += 1
    console.log(` - ${p.slice(0, 60)}: ${kind} (${cfg.tables.map((t) => t.label).join(', ')}), wanted ${ok.join(' or ')}`)
  }
  if (!cfg.tables.length || !cfg.kpis.length) { bad += 1; console.log(` - ${p.slice(0, 60)}: an empty dashboard`) }
  else if (!cfg.charts.some((c) => c.kind === 'status') || !cfg.charts.some((c) => c.kind !== 'status')) { bad += 1; console.log(` - ${p.slice(0, 60)}: the overview lacks a chart by status or a chart by month`) }
}
console.log(`app-kinds: ${CASES.length * 2 - bad} checks passed, ${bad} failed`)

// Turns src/generator/motionRuntime.ts into plain JavaScript text (src/generator/motionRuntimeJs.ts), so the
// standalone .html export can run the very same animation code without a build step. Runs before dev and build.
import fs from 'node:fs'
import ts from 'typescript'

const source = fs.readFileSync('src/generator/motionRuntime.ts', 'utf8')
const { outputText } = ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, verbatimModuleSyntax: false },
})
const js = outputText.replace(/^export /gm, '').replace(/^import .*$/gm, '').trim()
fs.writeFileSync(
  'src/generator/motionRuntimeJs.ts',
  `// GENERATED by scripts/gen-runtime.mjs from motionRuntime.ts. Do not edit; run "npm run gen".\nexport const MOTION_RUNTIME_JS = ${JSON.stringify(js)}\n`,
)
console.log('motionRuntimeJs.ts written,', js.length, 'chars')

// the widgets (countdown, order list ...) run in the exports as plain JavaScript too
const widgetSource = fs.readFileSync('src/generator/library/widgetRuntime.ts', 'utf8')
